import { existsSync, statSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import type { SkillRunEnd } from "../background-skills.ts";
import { CaptureError, plainDirState, type CaptureResult } from "./capture.ts";
import { reportFile } from "./state.ts";

/**
 * What the chat says of a capture the person started with /capture: why it does not start, that it started, and how it
 * ended - its end coming back to the chat as a background skill's does, the chat's agent told to pass the report on.
 */

/** Why a capture of `root` cannot start, or undefined when it can - a stopped one goes on. */
export function captureRefusal(root: string): string | undefined {
  if (!existsSync(root) || !statSync(root).isDirectory()) return `${root} is not a folder. Nothing was started.`;
  const plainDir = join(root, "plain");
  const found = plainDirState(plainDir);
  if (found.kind === "finished") return `${plainDir} holds a finished capture already - its report is ${reportFile(plainDir)}. Move that folder out of the way to capture again. Nothing was started.`;
  if (found.kind === "taken") return `${found.why}: capture writes its ***plain into a folder of its own, plain/. Nothing was started.`;
  return undefined;
}

export function captureStartedText(root: string, goesOn: boolean): string {
  return [
    `${goesOn ? "Going on with the capture" : "Capturing"} ${root} into ${join(root, "plain")}, in the background.`,
    "Nothing is asked: what it decides, leaves out or cannot capture is in its report, which comes back to this chat when it ends.",
  ].join(" ");
}

/** Whether a capture of `root` was started before and stopped: it goes on from where it was. */
export function captureGoesOn(root: string): boolean {
  return plainDirState(join(root, "plain")).kind === "resume";
}

/**
 * A capture's end, for the chat it is told in: the chat it was started in, or the turri opened again in its ***plain's
 * folder (`cwd` is then `plainDir`). A chat works on the project of its own folder, so from another the ***plain is
 * regenerated by opening turri in its folder.
 */
export function captureEnded(cwd: string, result: Pick<CaptureResult, "plainDir" | "reportFile" | "summary">): SkillRunEnd {
  const shown = (path: string) => relative(cwd, path) || path;
  const elsewhere = resolve(result.plainDir) !== resolve(cwd);
  const open = `cd ${shown(result.plainDir)} && turri`;
  return {
    skill: "capture",
    ok: true,
    line: `Capture finished: ${result.summary} The report: ${shown(result.reportFile)}.${elsewhere ? ` To review and regenerate it, open turri in its folder: ${open}.` : ""}`,
    task: [
      `The capture the person started with /capture finished: ${result.summary}`,
      `Its report is ${result.reportFile}. Read it, then tell the person in a few lines: the modules written, what could not be captured or was left out, the options, commands and routes of the code its ***plain names nowhere, and what the capture was unsure of.`,
      `The ***plain in ${result.plainDir} is the source of truth from now on: they read it first, then regenerate it, its first module first. The report says whether its testing scripts were written; any it lacks, start their skill for - implement-unit-testing-script, implement-conformance-testing-script - before it is regenerated. Change no ***plain and regenerate nothing until they say.`,
      ...(elsewhere ? [`It is a project of its own, which this chat does not work on: tell them to open turri in its folder to review and regenerate it - \`${open}\`.`] : []),
    ].join("\n"),
  };
}

/** What the person is asked once a capture in the chat ends: to open turri again in the captured project. */
export function captureOpenQuestion(cwd: string, result: Pick<CaptureResult, "plainDir" | "summary">): { title: string; message: string } {
  const folder = `${relative(cwd, result.plainDir) || result.plainDir}/`;
  return {
    title: `Open the captured ***plain in ${folder}?`,
    message: [
      result.summary,
      "",
      `turri closes here and opens again in ${folder} - the captured project - where ctrl+h shows its ***plain and /regenerate builds it. Its report is told there.`,
      `Not now: it stays here, and \`cd ${folder.slice(0, -1)} && turri\` opens it later.`,
    ].join("\n"),
  };
}

/** What a turri opened again after a capture is told at its start: what the capture said of itself. */
export function reopenedAfterCapture(summary: string): string {
  return JSON.stringify({ summary });
}

/** What a turri opened again after a capture was told, or undefined when it is not that turri. */
export function readReopenedAfterCapture(told: string | undefined): { summary: string } | undefined {
  if (told === undefined) return undefined;
  try {
    const parsed = JSON.parse(told) as { summary?: unknown };
    return typeof parsed.summary === "string" ? { summary: parsed.summary } : undefined;
  } catch {
    return undefined;
  }
}

export function captureFailed(error: unknown): SkillRunEnd {
  const why = error instanceof Error ? error.message : String(error);
  return {
    skill: "capture",
    ok: false,
    line: `Capture stopped: ${why}`,
    task: [
      `The capture the person started with /capture stopped: ${why}`,
      error instanceof CaptureError
        ? "Tell the person in a line or two."
        : "Tell the person in a line or two. What it captured before it stopped is kept: /capture again goes on from where it was.",
    ].join("\n"),
  };
}
